export const LEVELS: Record<number, LevelConfig> = Object.fromEntries(
  LEVEL_LIST.map((level) => [level.id, level]),
);

export const LEVEL_COUNT = LEVEL_LIST.length;

export function getLevel(id: number): LevelConfig {
  return LEVELS[id] ?? LEVEL_LIST[0]!;
}

export function getLevelTitle(id: number): string {
  return LEVEL_TITLES[id - 1] ?? `Level ${id}`;
}

export function getStarThresholds(level: LevelConfig): [number, number, number] {
  const target = level.goal.target;
  const base = Math.round(target * 2);
  return [base, Math.round(base * 1.35), Math.round(base * 1.7)];
}
